"""The final SQLite schema, built once in Postgres.

The SQLite migrations in db.py and models/ stay the one source of truth: a throwaway SQLite database is
migrated to the current version, then each of its objects is translated. Tables come in dependency order
with BIGINT identities; COLLATE NOCASE uniqueness becomes a unique index on LOWER(); the 124 rule triggers
become PL/pgSQL functions raising the same messages; and a `sqlite_master` view answers the services'
"does this table exist?" checks.
"""
import re
import sqlite3
import tempfile
from contextlib import contextmanager
from pathlib import Path

import sqlglot

from pgcompat.translate import to_postgres

META = 'nimus_meta'

_TRIGGER = re.compile(r"CREATE TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(INSERT|UPDATE|DELETE)(?:\s+OF\s+([\w,\s]+?))?\s+ON\s+(\w+)"
                      r"(?:\s+FOR EACH ROW)?(?:\s+WHEN\s+(.*?))?\s+BEGIN\s+(.*)\s*END\s*;?$", re.S | re.I)
_MESSAGE = r"'((?:[^']|'')*)'"
_RAISE_ONLY = re.compile(r"^SELECT\s+RAISE\s*\(\s*ABORT\s*," + _MESSAGE + r"\s*\)\s*(?:WHERE\s+(.*))?$", re.S | re.I)
_CASE_RAISE = re.compile(r"^SELECT\s+CASE\s+WHEN\s+(.*)\s+THEN\s+RAISE\s*\(\s*ABORT\s*," + _MESSAGE + r"\s*\)\s+END$", re.S | re.I)

COMPAT_FUNCTIONS = [
    # Triggers ask whether the write is a reconciliation; db.connect(reconciliation=True) sets it per transaction.
    """CREATE OR REPLACE FUNCTION nimus_reconciling() RETURNS integer LANGUAGE sql STABLE AS
       $$ SELECT COALESCE(NULLIF(current_setting('nimus.reconciling', true), ''), '0')::integer $$""",
    # SQLite's json_valid(), used by CHECK constraints on JSON payload columns.
    """CREATE OR REPLACE FUNCTION json_valid(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS
       $$ BEGIN PERFORM value::jsonb; RETURN true; EXCEPTION WHEN others THEN RETURN false; END $$""",
]

SQLITE_MASTER_VIEW = """CREATE OR REPLACE VIEW sqlite_master AS
    SELECT 'table'::text AS type, c.relname::text AS name, c.relname::text AS tbl_name, NULL::text AS sql
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = current_schema() AND c.relkind IN ('r', 'p')
    UNION ALL SELECT 'view', viewname::text, viewname::text, NULL FROM pg_views
     WHERE schemaname = current_schema() AND viewname <> 'sqlite_master'
    UNION ALL SELECT 'index', indexname::text, tablename::text, NULL FROM pg_indexes WHERE schemaname = current_schema()
    UNION ALL SELECT 'trigger', t.tgname::text, c.relname::text, NULL FROM pg_trigger t
      JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = current_schema() AND NOT t.tgisinternal"""


def objects(conn):
    """A SQLite database's schema objects, in creation order."""
    return conn.execute("SELECT type, name, tbl_name, sql FROM sqlite_master "
                        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()


@contextmanager
def sqlite_reference():
    """A temporary SQLite database migrated to the current schema, with the rows its migrations seed."""
    import db
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / 'schema.db'
        db.init_db(path)
        conn = sqlite3.connect(path)
        try:
            yield conn
        finally:
            conn.close()


def _sql(text):
    """A DDL statement or expression in Postgres, without psycopg parameter escaping."""
    return to_postgres(text).replace('%%', '%')


def _ddl(text):
    """DDL: NULLS FIRST only means something in ORDER BY, never in keys or indexes."""
    return _sql(text).replace(' NULLS FIRST', '')


def _table(sql):
    """CREATE TABLE in Postgres: BIGINT ids and amounts, and SQLite-only checks dropped."""
    sql = re.sub(r"TYPEOF\s*\(\s*\w+\s*\)\s*=\s*'integer'\s*(AND\s+)?", '', sql, flags=re.I)
    sql = re.sub(r"\bCHECK\s*\(\s*\)", '', sql)
    nocase = re.findall(r"(\w+)\s+TEXT[^,]*?COLLATE\s+NOCASE[^,]*?UNIQUE|(\w+)\s+TEXT[^,]*?UNIQUE[^,]*?COLLATE\s+NOCASE", sql, re.I)
    sql = re.sub(r"\s+COLLATE\s+NOCASE", '', sql, flags=re.I)
    unique_nocase = [a or b for a, b in nocase]
    for column in unique_nocase:
        sql = re.sub(rf"(\b{column}\s+TEXT[^,]*?)\s+UNIQUE", r'\1', sql, count=1, flags=re.I)
    # Column types only: casts (`AS INT`) keep INT, which booleans can be converted to.
    out = re.sub(r"(?<!AS )\bINT\b", 'BIGINT', _ddl(sql))
    # SQLite's INTEGER PRIMARY KEY hands out ids by itself even without AUTOINCREMENT.
    out = re.sub(r"\b(\w+) BIGINT (?:NOT NULL )?PRIMARY KEY\b", r"\1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
    # Deferrable references let a bulk copy load rows in any order and check them all at commit.
    out = re.sub(r"(REFERENCES \w+ \([^)]*\)(?:\s+ON (?:DELETE|UPDATE) (?:CASCADE|RESTRICT|SET NULL|SET DEFAULT|NO ACTION))*)",
                 r"\1 DEFERRABLE INITIALLY IMMEDIATE", out)
    return out, unique_nocase


def _references(sql):
    return {t.lower() for t in re.findall(r"REFERENCES\s+\"?(\w+)", sql, re.I)}


def _expression(text):
    return _sql('SELECT ' + text)[len('SELECT '):]


def _statement(text):
    """One statement of a trigger body in PL/pgSQL."""
    text = text.strip()
    if m := _RAISE_ONLY.match(text):
        message, condition = m.group(1), m.group(2)
        raise_ = f"RAISE EXCEPTION USING MESSAGE = '{message}', ERRCODE = 'P0001';"
        return f"IF {_expression(condition)} THEN {raise_} END IF;" if condition else raise_
    if m := _CASE_RAISE.match(text):
        return f"IF {_expression(m.group(1))} THEN RAISE EXCEPTION USING MESSAGE = '{m.group(2)}', ERRCODE = 'P0001'; END IF;"
    return _sql(text) + ';'


def _split(body):
    """Statements of a trigger body, split on semicolons outside quotes and parentheses."""
    parts, depth, quoted, current = [], 0, False, []
    for char in body:
        if char == "'":
            quoted = not quoted
        elif not quoted and char == '(':
            depth += 1
        elif not quoted and char == ')':
            depth -= 1
        if char == ';' and not quoted and depth == 0:
            parts.append(''.join(current)); current = []
        else:
            current.append(char)
    parts.append(''.join(current))
    return [p for p in parts if p.strip()]


def trigger(sql):
    """A SQLite rule trigger as a PL/pgSQL function and its trigger, same timing, columns and messages."""
    m = _TRIGGER.match(sql.strip())
    if not m:
        raise ValueError(f'Disparador sin traducir: {sql[:120]}')
    name, timing, event, columns, table, when, body = m.groups()
    statements = '\n    '.join(_statement(s) for s in _split(body))
    if when:
        statements = f"IF {_expression(when)} THEN\n    {statements}\n  END IF;"
    returned = 'NULL' if timing.upper() == 'AFTER' else ('OLD' if event.upper() == 'DELETE' else 'NEW')
    of = f" OF {', '.join(c.strip() for c in columns.split(','))}" if columns else ''
    function = (f"CREATE OR REPLACE FUNCTION trg_{name}() RETURNS trigger LANGUAGE plpgsql AS $fn$\nBEGIN\n  {statements}\n"
                f"  RETURN {returned};\nEND $fn$")
    create = f"CREATE TRIGGER {name} {timing.upper()} {event.upper()}{of} ON {table} FOR EACH ROW EXECUTE FUNCTION trg_{name}()"
    return [function, create]


def statements(rows):
    """Every Postgres statement for the SQLite objects, in an order Postgres accepts."""
    tables = {name.lower(): sql for kind, name, _, sql in rows if kind == 'table'}
    ordered, seen = [], set()

    def visit(name, path=()):
        if name in seen or name not in tables:
            return
        for ref in sorted(_references(tables[name]) - {name}):
            if ref not in path:
                visit(ref, path + (name,))
        seen.add(name)
        ordered.append(name)

    for name in tables:
        visit(name)
    out = list(COMPAT_FUNCTIONS)
    for name in ordered:
        ddl, nocase = _table(tables[name])
        out.append(ddl)
        out.extend(f"CREATE UNIQUE INDEX {name}_{column}_nocase ON {name} (LOWER({column}))" for column in nocase)
    for kind, name, _, sql in rows:
        if kind == 'index':
            out.append(_ddl(re.sub(r"\s+COLLATE\s+NOCASE", '', sql, flags=re.I)))
        elif kind == 'view':
            out.append(_sql(sql))
    for kind, name, _, sql in rows:
        if kind == 'trigger':
            out.extend(trigger(sql))
    out.append(SQLITE_MASTER_VIEW)
    out.append(SQLITE_SEQUENCE_VIEW)
    out.append(f"CREATE TABLE {META} (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
    return out


# sqlite_sequence: the last id handed out per table, which production._code reads to never reuse a folio.
SQLITE_SEQUENCE_VIEW = """CREATE OR REPLACE VIEW sqlite_sequence AS
    SELECT regexp_replace(sequencename::text, '_id_seq$', '') AS name, last_value AS seq
      FROM pg_sequences WHERE schemaname = current_schema() AND last_value IS NOT NULL"""


def table_order(rows):
    """Tables in the order the schema creates them (referenced tables first)."""
    return [s.split()[2].strip('"') for s in statements(rows) if s.startswith('CREATE TABLE ') and not s.startswith(f'CREATE TABLE {META}')]


def copy_tables(source, raw, tables, *, sequences=None):
    """Copy every row of `tables` from a SQLite connection into Postgres, keeping ids, inside raw's transaction.

    Rule triggers are paused during the copy (a delivered order must be loadable with its pieces) and
    references are checked once at commit. Each identity then resumes after the highest id, or after
    SQLite's own counter when deleted rows had gone further. Returns {table: rows copied}.
    """
    counts = {}
    sequences = sequences if sequences is not None else dict(source.execute('SELECT name, seq FROM sqlite_sequence').fetchall()
                                                            if source.execute("SELECT 1 FROM sqlite_master WHERE name='sqlite_sequence'").fetchone() else [])
    # Everything below is one transaction: if any step fails, the rollback also restores the paused triggers.
    raw.execute('SET CONSTRAINTS ALL DEFERRED')
    for table in tables:
        raw.execute(f'ALTER TABLE {table} DISABLE TRIGGER USER')
    for table in tables:
        columns = [r[1] for r in source.execute(f'PRAGMA table_info("{table}")')]
        names = ', '.join(columns)
        rows = source.execute(f'SELECT {", ".join(chr(34) + c + chr(34) for c in columns)} FROM "{table}"').fetchall()
        if rows:
            with raw.cursor().copy(f'COPY {table} ({names}) FROM STDIN') as copy:
                for row in rows:
                    copy.write_row(row)
        counts[table] = len(rows)
    identity = {r[0] for r in raw.execute("SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema() "
                                           "AND column_name = 'id' AND is_identity = 'YES'").fetchall()}
    for table in tables:
        if table in identity:
            highest = max(raw.execute(f'SELECT COALESCE(MAX(id), 0) FROM {table}').fetchone()[0], sequences.get(table) or 0)
            raw.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), %s, %s)", (max(highest, 1), highest > 0))
    # Every reference is checked now, before the rules come back on.
    raw.execute('SET CONSTRAINTS ALL IMMEDIATE')
    for table in tables:
        raw.execute(f'ALTER TABLE {table} ENABLE TRIGGER USER')
    return counts


def ensure(raw, *, seed=True):
    """Build the schema in an empty Postgres database, or check that an existing one is current.

    `raw` is a psycopg connection in autocommit mode. With seed, the default rows a new SQLite database
    gets (machines, accounts, settings) come along; a migration of real data builds it without them.
    Returns the schema version.
    """
    import db
    present = raw.execute("SELECT to_regclass(%s)", (f'{META}',)).fetchone()[0]
    if present:
        version = int(raw.execute(f"SELECT value FROM {META} WHERE key='schema_version'").fetchone()[0])
        if version != db.SCHEMA_VERSION:
            raise RuntimeError(f'La base Postgres está en la versión {version} y la app espera {db.SCHEMA_VERSION}: '
                               'aplica la migración de esquema antes de usarla.')
        return version
    with sqlite_reference() as reference:
        rows = objects(reference)
        version = reference.execute('PRAGMA user_version').fetchone()[0]
        with raw.transaction():
            for statement in statements(rows):
                raw.execute(statement)
            if seed:
                # The rows the migrations seed (default machines, accounts, settings) come along.
                copy_tables(reference, raw, table_order(rows))
            raw.execute(f"INSERT INTO {META}(key, value) VALUES ('schema_version', %s)", (str(version),))
    return version

"""Sign-in for the cloud app: users with scrypt passwords and a signed session cookie.

The local Streamlit app has no sign-in because it only opens on the workshop's computer; online, every
route except the sign-in itself requires a session.

- Passwords: hashlib.scrypt with a random salt (standard library, nothing to install).
- Session: an httpOnly, Secure, SameSite=Lax cookie holding the user id and expiry, signed with NIMUS_SECRET.
- Writes also require the X-NIMUS header, which only the app's own fetch calls send: a form posted from
  another site cannot carry it.
- Roles: admin (everything) and taller (production, no finances).
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import secrets
import time

from fastapi import Depends, HTTPException, Request, Response

COOKIE = 'nimus_session'
SESSION_SECONDS = 7 * 24 * 3600
ROLES = ('admin', 'taller')

USERS_TABLE = """CREATE TABLE IF NOT EXISTS nimus_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'taller')),
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_at TEXT NOT NULL)"""
USERS_INDEX = 'CREATE UNIQUE INDEX IF NOT EXISTS nimus_users_email ON nimus_users (LOWER(email))'


def _secret() -> bytes:
    value = os.environ.get('NIMUS_SECRET', '')
    if len(value) < 32:
        raise RuntimeError('Falta NIMUS_SECRET (al menos 32 caracteres) en las variables de entorno.')
    return value.encode()


def hash_password(password: str) -> str:
    if len(password) < 10:
        raise ValueError('La contraseña debe tener al menos 10 caracteres.')
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=2 ** 14, r=8, p=1, dklen=32)
    return 'scrypt$' + base64.b64encode(salt).decode() + '$' + base64.b64encode(digest).decode()


def check_password(password: str, stored: str) -> bool:
    try:
        _, salt, digest = stored.split('$')
        expected = base64.b64decode(digest)
        actual = hashlib.scrypt(password.encode(), salt=base64.b64decode(salt), n=2 ** 14, r=8, p=1, dklen=len(expected))
    except (ValueError, TypeError):
        return False
    return hmac.compare_digest(actual, expected)


def sign(user_id: int, expires: int | None = None) -> str:
    payload = base64.urlsafe_b64encode(json.dumps({'uid': user_id, 'exp': expires or int(time.time()) + SESSION_SECONDS}).encode()).decode()
    mac = hmac.new(_secret(), payload.encode(), hashlib.sha256).hexdigest()
    return f'{payload}.{mac}'


def read(token: str | None) -> int | None:
    """The user id in a valid, unexpired session token; None otherwise."""
    if not token or '.' not in token:
        return None
    payload, mac = token.rsplit('.', 1)
    if not hmac.compare_digest(mac, hmac.new(_secret(), payload.encode(), hashlib.sha256).hexdigest()):
        return None
    try:
        data = json.loads(base64.urlsafe_b64decode(payload.encode()))
    except ValueError:
        return None
    return int(data['uid']) if data.get('exp', 0) > time.time() else None


def ensure_users(conn) -> None:
    """The users table, and the first administrator from NIMUS_ADMIN_EMAIL / NIMUS_ADMIN_PASSWORD when there is none."""
    raw = conn._raw
    raw.execute(USERS_TABLE)
    raw.execute(USERS_INDEX)
    if raw.execute('SELECT EXISTS(SELECT 1 FROM nimus_users)').fetchone()[0]:
        return
    email, password = os.environ.get('NIMUS_ADMIN_EMAIL', '').strip(), os.environ.get('NIMUS_ADMIN_PASSWORD', '')
    if email and password:
        raw.execute('INSERT INTO nimus_users (email, name, password_hash, role, created_at) VALUES (%s, %s, %s, %s, %s)',
                    (email, 'Administrador', hash_password(password), 'admin', time.strftime('%Y-%m-%d %H:%M:%S')))


def create_user(email: str, password: str, *, role: str = 'taller', name: str = '') -> int:
    import db
    if role not in ROLES:
        raise ValueError('Rol no válido: admin o taller.')
    email = email.strip()
    if '@' not in email:
        raise ValueError('Escribe un correo válido.')
    with db.connect(write=True) as conn:
        ensure_users(conn)
        if conn._raw.execute('SELECT 1 FROM nimus_users WHERE LOWER(email) = LOWER(%s)', (email,)).fetchone():
            raise ValueError('Ya existe un usuario con ese correo.')
        return conn._raw.execute('INSERT INTO nimus_users (email, name, password_hash, role, created_at) VALUES (%s, %s, %s, %s, %s) RETURNING id',
                                 (email, name, hash_password(password), role, time.strftime('%Y-%m-%d %H:%M:%S'))).fetchone()[0]


def authenticate(email: str, password: str):
    import db
    with db.connect(write=True) as conn:
        ensure_users(conn)
        row = conn._raw.execute('SELECT id, email, name, role, active, password_hash FROM nimus_users WHERE LOWER(email) = LOWER(%s)',
                                (email.strip(),)).fetchone()
    if not row or not row[4] or not check_password(password, row[5]):
        time.sleep(0.4)  # Same pace for a wrong user or a wrong password.
        return None
    return dict(id=row[0], email=row[1], name=row[2], role=row[3])


def user_by_id(user_id: int):
    import db
    with db.connect() as conn:
        row = conn._raw.execute('SELECT id, email, name, role, active FROM nimus_users WHERE id = %s', (user_id,)).fetchone()
    return dict(id=row[0], email=row[1], name=row[2], role=row[3]) if row and row[4] else None


def set_session(response: Response, user_id: int) -> None:
    response.set_cookie(COOKIE, sign(user_id), max_age=SESSION_SECONDS, httponly=True, samesite='lax',
                        secure=os.environ.get('NIMUS_INSECURE_COOKIE') != '1', path='/')


def clear_session(response: Response) -> None:
    response.delete_cookie(COOKIE, path='/')


def current_user(request: Request):
    """The signed-in user; 401 otherwise. Writes must also carry the app's X-NIMUS header."""
    user_id = read(request.cookies.get(COOKIE))
    user = user_by_id(user_id) if user_id else None
    if not user:
        raise HTTPException(status_code=401, detail='Inicia sesión para continuar.')
    if request.method not in ('GET', 'HEAD', 'OPTIONS') and request.headers.get('x-nimus') != '1':
        raise HTTPException(status_code=403, detail='Solicitud no válida.')
    return user


def admin(user=Depends(current_user)):
    if user['role'] != 'admin':
        raise HTTPException(status_code=403, detail='Esta sección es solo para administración.')
    return user

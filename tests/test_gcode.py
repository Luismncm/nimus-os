import io
import unittest
from services import gcode


class GcodeTest(unittest.TestCase):
    def test_bambu_or_orca_header(self):
        text = """; HEADER_BLOCK_START
; BambuStudio 1.9.0
; total layer number: 123
; total filament length [mm] : 1234.56
; total filament weight [g] : 45.67
; model printing time: 2h 35m 12s
; total estimated time: 2h 40m 0s
; HEADER_BLOCK_END
G28
"""
        result = gcode.parse(text)
        self.assertEqual(result, dict(minutes=160, grams=45.67, found=True))

    def test_bambu_multicolor_sums_every_extruder(self):
        text="; total filament weight [g] : 20.10, 5.25, 0.00\n; total estimated time: 1h 10m 0s\n"
        result=gcode.parse(text)
        self.assertEqual((result['grams'],result['minutes']),(25.35,70))

    def test_prusaslicer_footer(self):
        text = """; generated by PrusaSlicer 2.7.0
G1 X1 Y1
...
; filament used [g] = 12.34
; filament used [mm] = 4123.00
; estimated printing time (normal mode) = 45m 12s
"""
        result = gcode.parse(text)
        self.assertEqual(result, dict(minutes=46, grams=12.34, found=True))

    def test_cura_seconds_and_grams(self):
        text = ";FLAVOR:Marlin\n;TIME:5430\n;Filament weight = 18.2 g\n;Layer height: 0.2\n"
        result = gcode.parse(text)
        self.assertEqual(result, dict(minutes=91, grams=18.2, found=True))

    def test_duration_with_days(self):
        text = "; total estimated time: 1d 2h 3m\n"
        self.assertEqual(gcode.parse(text)['minutes'], 1440 + 120 + 3)

    def test_no_recognizable_comments_returns_nothing_found(self):
        self.assertEqual(gcode.parse('G28\nG1 X10 Y10\n'), dict(minutes=None, grams=None, found=False))

    def test_parse_file_reads_an_uploaded_object(self):
        upload = io.BytesIO('; total filament weight [g] : 8.5\n; total estimated time: 20m 0s\n'.encode('utf-8'))
        result = gcode.parse_file(upload)
        self.assertEqual((result['grams'], result['minutes']), (8.5, 20))


if __name__ == '__main__':
    unittest.main()
